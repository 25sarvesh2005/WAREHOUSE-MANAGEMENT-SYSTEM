"""
Pydantic schemas for webhook subscriptions, delivery tracking, and inbound ingestion.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field


class WebhookSubscriptionCreate(BaseModel):
    """Payload to register a new webhook destination."""

    model_config = ConfigDict(extra="forbid")

    url: str = Field(..., min_length=8, max_length=1000, description="HTTPS endpoint URL")
    secret: str | None = Field(None, min_length=16, max_length=255, description="HMAC secret; autogenerated if omitted")
    event_types: list[str] = Field(default_factory=lambda: ["*"], description="Subscribed event types or '*' for all")
    description: str | None = Field(None, max_length=255)


class WebhookSubscriptionResponse(BaseModel):
    """Public representation of a webhook subscription."""

    model_config = ConfigDict(from_attributes=True)

    id: UUID
    tenant_id: str
    url: str
    secret: str
    event_types: list[str]
    status: str
    description: str | None
    created_at: datetime


class WebhookDeliveryResponse(BaseModel):
    """Audit log entry for an outbound webhook attempt."""

    model_config = ConfigDict(from_attributes=True)

    id: UUID
    subscription_id: UUID
    outbox_event_id: UUID | None
    event_type: str
    payload: dict[str, Any]
    status_code: int | None
    response_body: str | None
    latency_ms: float | None
    attempt_number: int
    error: str | None
    delivered_at: datetime


class InboundCarrierWebhookRequest(BaseModel):
    """Payload for carrier delivery tracking webhooks."""

    tracking_number: str = Field(..., min_length=4, max_length=100)
    carrier: str = Field(..., min_length=2, max_length=50)
    event_status: str = Field(..., description="IN_TRANSIT, OUT_FOR_DELIVERY, DELIVERED, EXCEPTION")
    location: str | None = None
    notes: str | None = None
    timestamp: datetime | None = None


class InboundOrderWebhookRequest(BaseModel):
    """Payload for external marketplace order intake."""

    external_order_id: str = Field(..., min_length=1, max_length=100)
    source: str = Field("DIRECT", max_length=50)
    seller_tenant_id: str
    customer_name: str
    shipping_address: dict[str, Any] = Field(default_factory=dict)
    lines: list[dict[str, Any]] = Field(default_factory=list)

